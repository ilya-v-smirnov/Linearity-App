write_grid <- function(path, sheet, values) {
    wb <- openxlsx::loadWorkbook(path)
    openxlsx::writeData(wb, sheet, as.data.frame(values), startRow = 2, startCol = 2, colNames = FALSE)
    openxlsx::saveWorkbook(wb, path, overwrite = TRUE)
}

filled_plate_maps <- function() {
    layout <- LinearityApp:::plate_layout_codes(96, 6, 2, 4)
    conc <- c(32, 16, 8, 4, 2, 1)
    path <- tempfile(fileext = '.xlsx')
    make_plate_maps(path, layout, conc)
    od <- matrix(NA, 8, 12)
    od[1:7, 1:2] <- c(0.1 * conc + 0.05, 0.05)
    od[1:4, 3] <- c('0,55', '1.05', '2.05', '0.3')
    write_grid(path, 'OD', od)
    name <- matrix(NA, 8, 12)
    name[1:4, 3] <- c('A', 'A', 'B', 'C')
    write_grid(path, 'sample.name', name)
    dil <- matrix(NA, 8, 12)
    dil[1:4, 3] <- c(1, 1, 2, 1)
    write_grid(path, 'dilution', dil)
    list(path = path, layout = layout, conc = conc)
}

test_that('plate maps template has a grid per column filled from the layout', {
    layout <- LinearityApp:::plate_layout_codes(96, 7, 2, 10, standards = 'after')
    conc <- 100 / 2^(0:6)
    path <- tempfile(fileext = '.xlsx')
    make_plate_maps(path, layout, conc)
    sheets <- readxl::excel_sheets(path)
    expect_equal(sheets, c('sample.name', 'sample.date', 'type', 'dilution', 'conc', 'OD'))
    type <- LinearityApp:::read_grid(path, 'type')
    expect_equal(unname(type[, 1]), rep('sample', 8))
    expect_equal(unname(type[, 3]), c(rep('standard', 7), 'blank'))
    conc_grid <- LinearityApp:::read_grid(path, 'conc')
    expect_equal(as.numeric(conc_grid[1:7, 3]), conc)
    expect_true(is.na(conc_grid[8, 3]))
    expect_equal(unname(LinearityApp:::read_grid(path, 'sample.name')[, 1]), rep('X', 8))
    expect_true(is.na(LinearityApp:::read_grid(path, 'sample.name')[1, 3]))
    expect_equal(sum(LinearityApp:::read_grid(path, 'OD') == 'X', na.rm = TRUE), sum(!is.na(layout)))
    expect_true(LinearityApp:::is_plate_maps_workbook(path))
    expect_false(LinearityApp:::is_plate_maps_workbook(sample_path('bca_plate.xlsx')))
})

test_that('filled plate maps are read and calculated', {
    x <- filled_plate_maps()
    data <- check_assay(read_assay(x$path))
    expect_equal(data$well[1:3], c('A1', 'A2', 'A3'))
    expect_equal(sum(data$type == 'standard'), 12)
    expect_equal(sum(data$type == 'blank'), 2)
    expect_equal(data$OD[data$well == 'A3'], 0.55)
    expect_equal(data$conc[data$well == 'B1'], 16)
    r <- calculate(data, 'LRM', linear = TRUE, round_fun = function(x, ...) x)
    expect_equal(r$result$conc, c(5, 10, 40, 2.5), tolerance = 1e-8)
    expect_equal(r$result$sample.name, c('A', 'A', 'B', 'C'))
    # sample.date was not filled in: placeholders are reported and ignored
    problems <- problems_table(attr(data, 'problems'), 'en')
    expect_match(paste(problems[[3]], collapse = ' '), 'placeholder X', fixed = TRUE)
})

test_that('new sheets become columns; orphan values and bad numbers are reported', {
    x <- filled_plate_maps()
    wb <- openxlsx::loadWorkbook(x$path)
    openxlsx::cloneWorksheet(wb, 'Group', 'sample.name')
    openxlsx::saveWorkbook(wb, x$path, overwrite = TRUE)
    group <- matrix(NA, 8, 12)
    group[1:4, 3] <- c('ctrl', 'ctrl', 'trt', 'trt')
    group[1, 10] <- 'stray'
    write_grid(x$path, 'Group', group)
    od <- matrix(NA, 8, 12)
    od[1:7, 1:2] <- c(0.1 * x$conc + 0.05, 0.05)
    od[1:4, 3] <- c('0.55', 'n/a', '2.05', '0.3')
    write_grid(x$path, 'OD', od)

    data <- read_assay(x$path)
    expect_equal(data$Group[data$type == 'sample'], c('ctrl', 'ctrl', 'trt', 'trt'))
    expect_true(is.na(data$OD[data$well == 'B3']))
    problems <- paste(problems_table(attr(data, 'problems'), 'en')[[3]], collapse = ' ')
    expect_match(problems, 'without a type are ignored: A10', fixed = TRUE)
    expect_match(problems, "Non-numeric value 'n/a' on sheet OD", fixed = TRUE)
})

test_that('plate maps with grids of different sizes are rejected', {
    x <- filled_plate_maps()
    wb <- openxlsx::loadWorkbook(x$path)
    openxlsx::addWorksheet(wb, 'extra')
    openxlsx::writeData(wb, 'extra', t(as.character(1:6)), startCol = 2, startRow = 1, colNames = FALSE)
    openxlsx::writeData(wb, 'extra', LETTERS[1:4], startCol = 1, startRow = 2, colNames = FALSE)
    openxlsx::saveWorkbook(wb, x$path, overwrite = TRUE)
    expect_error(check_assay(read_assay(x$path)), 'differs in size')
})

test_that('long table template follows the layout', {
    layout <- LinearityApp:::plate_layout_codes(96, 5, 1, 3, by = 'row')
    long <- make_long_table(layout, conc = c(10, 5, 2.5, 1.25, 0.625), by = 'row')
    expect_equal(long$well[1:6], c('A1', 'A2', 'A3', 'A4', 'A5', 'A6'))
    expect_equal(long$type, c(rep('standard', 5), 'blank', rep('sample', 3)))
    expect_equal(long$conc[1:5], c(10, 5, 2.5, 1.25, 0.625))
    expect_equal(long$dilution, c(rep(NA, 6), 1, 1, 1))
})
